func TestStartRegistersWebhook(t *testing.T) {
	var sawPath string
	var payload map[string]any
	client := &http.Client{Transport: testRoundTripFunc(func(req *http.Request) (*http.Response, error) {
		sawPath = req.URL.Path
		if err := json.NewDecoder(req.Body).Decode(&payload); err != nil {
			t.Fatalf("decode setWebhook payload: %v", err)
		}
		return testJSONResponseObj(map[string]any{"ok": true, "result": true})
	})}
	runtime := makeRuntime(&fakeSDKGateway{}, newFakeSDKAccountStore(), sdkAccount("acct-1"))
	runtime.Webhook = &sdk.WebhookEndpoint{URL: "https://beak.example/api/v1/channel-webhooks/telegram/acct-1"}
	runtime.HTTPClient = client

	if err := (Connector{}).Start(context.Background(), runtime); err != nil {
		t.Fatalf("Start: %v", err)
	}
	if sawPath != "/bot"+testBotToken+"/setWebhook" {
		t.Fatalf("setWebhook path=%q", sawPath)
	}
	if payload["url"] != runtime.Webhook.URL || payload["secret_token"] != testWebhookSecret {
		t.Fatalf("setWebhook payload=%#v", payload)
	}
	if updates, ok := payload["allowed_updates"].([]any); !ok || len(updates) == 0 {
		t.Fatalf("allowed_updates=%#v", payload["allowed_updates"])
	}
}

